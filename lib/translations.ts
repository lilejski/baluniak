/** Flattened key path for t() – e.g. 'header.cta' or 'footer.nav' (returns array). */
type DotPath<T, P extends string = ""> = T extends object
  ? { [K in keyof T]: K extends string ? (T[K] extends object ? DotPath<T[K], `${P}${K}.`> : `${P}${K}`) : never }[keyof T] extends infer S
  ? S extends string
  ? S
  : never
  : never
  : never;

export type TranslationPath = DotPath<(typeof translations)["PL"]>;

/** Get nested value by dot path. */
function getByPath(obj: Record<string, unknown>, path: string): unknown {
  const parts = path.split(".");
  let current: unknown = obj;
  for (const p of parts) {
    if (current == null || typeof current !== "object") return undefined;
    current = (current as Record<string, unknown>)[p];
  }
  return current;
}

/** Translate by dot path. Use for simple keys; for arrays/objects (e.g. footer.nav) use translations[lang].footer.nav. */
export function t(lang: Language, path: string): string {
  const value = getByPath(translations[lang] as Record<string, unknown>, path);
  return typeof value === "string" ? value : (value as string) ?? path;
}

